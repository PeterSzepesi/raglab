CREATE TABLE papers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arxiv_id VARCHAR(64) NOT NULL,
    title TEXT NOT NULL,
    abstract_text TEXT NOT NULL,
    authors VARCHAR(1024) ARRAY NOT NULL,
    categories VARCHAR(50) ARRAY NOT NULL,
    submitted_date DATE,
    updated_date DATE,
    doi VARCHAR(255),
    journal_ref TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_papers_arxiv_id UNIQUE (arxiv_id)
);

CREATE INDEX idx_papers_submitted_date ON papers (submitted_date);
